function p(
  id: string,
  name: string,
  shortName: string,
  nationality: string,
  nationCode: string,
  clubId: string,
  clubName: string,
  seasonYear: string,
  pos: Position,
  secondaries: Position[],
  ovr: number,
  pac: number,
  sho: number,
  pas: number,
  dri: number,
  def: number,
  phy: number,
  gk: number,
  iq: number,
  foot: 'Left' | 'Right' | 'Both',
  badgeColor: string,
  accentColor: string,
  number?: number
): Player {
  return {
    id,
    name,
    shortName,
    nationality,
    nationCode,
    clubId,
    clubName,
    seasonYear,
    primaryPosition: pos,
    secondaryPositions: secondaries,
    overall: ovr,
    pace: pac,
    shooting: sho,
    passing: pas,
    dribbling: dri,
    defending: def,
    physical: phy,
    goalkeeping: gk,
    tacticalIQ: iq,
    preferredFoot: foot,
    rarity: ovr >= 90 ? 'Legendary' : ovr >= 84 ? 'Rare' : 'Standard',
    badgeColor,
    accentColor,
    number,
  };
}

